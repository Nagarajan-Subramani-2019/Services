CREATE TABLE UV_USER_CREDENTIALS (
    USER_ID NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    USERNAME VARCHAR2(100 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    RECORD_STATUS VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    UPDATED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    LAST_LOGIN_AT TIMESTAMP(6),
    CONSTRAINT PK_UV_USER_CREDENTIALS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_UV_USERNAME UNIQUE (USERNAME),
    CONSTRAINT CK_UV_CREDENTIAL_STATUS CHECK (RECORD_STATUS IN ('ACTIVE', 'CLOSED'))
);

CREATE TABLE UV_USER_DETAILS (
    USER_ID NUMBER(19) NOT NULL,
    FULL_NAME VARCHAR2(200 CHAR) NOT NULL,
    ADDRESS VARCHAR2(1000 CHAR) NOT NULL,
    RECORD_STATUS VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    UPDATED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT PK_UV_USER_DETAILS PRIMARY KEY (USER_ID),
    CONSTRAINT FK_UV_DETAILS_USER FOREIGN KEY (USER_ID) REFERENCES UV_USER_CREDENTIALS (USER_ID),
    CONSTRAINT CK_UV_DETAILS_STATUS CHECK (RECORD_STATUS IN ('ACTIVE', 'CLOSED'))
);

CREATE TABLE UV_LOGIN_STATISTICS (
    LOGIN_ID NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    USER_ID NUMBER(19),
    ATTEMPTED_USERNAME VARCHAR2(100 CHAR) NOT NULL,
    OUTCOME VARCHAR2(10 CHAR) NOT NULL,
    FAILURE_CODE VARCHAR2(30 CHAR),
    ATTEMPTED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    PROCESSING_TIME_MS NUMBER(14,3) NOT NULL,
    CONSTRAINT PK_UV_LOGIN_STATISTICS PRIMARY KEY (LOGIN_ID),
    CONSTRAINT FK_UV_LOGIN_USER FOREIGN KEY (USER_ID) REFERENCES UV_USER_CREDENTIALS (USER_ID),
    CONSTRAINT CK_UV_LOGIN_OUTCOME CHECK (OUTCOME IN ('SUCCESS', 'FAILED')),
    CONSTRAINT CK_UV_LOGIN_DURATION CHECK (PROCESSING_TIME_MS >= 0),
    CONSTRAINT CK_UV_LOGIN_SUCCESS_USER CHECK (OUTCOME = 'FAILED' OR USER_ID IS NOT NULL)
);

COMMENT ON COLUMN UV_USER_CREDENTIALS.PASSWORD_HASH IS 'Salted PBKDF2-HMAC-SHA256 hash; no plaintext passwords';
COMMENT ON COLUMN UV_LOGIN_STATISTICS.PROCESSING_TIME_MS IS 'Login processing duration in milliseconds; excludes HTTP transit and transaction commit';
COMMENT ON COLUMN UV_LOGIN_STATISTICS.USER_ID IS 'Null when a login attempt uses an unknown username';
