CREATE SCHEMA IF NOT EXISTS USER_INFO_SCHEMA;

CREATE TABLE IF NOT EXISTS USER_INFO_SCHEMA.USER_DETAILS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(64) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(254) NOT NULL UNIQUE,
    PHONE_NUMBER VARCHAR2(32) NOT NULL,
    USER_ROLE VARCHAR2(16) DEFAULT 'USER' NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MODIFIED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
