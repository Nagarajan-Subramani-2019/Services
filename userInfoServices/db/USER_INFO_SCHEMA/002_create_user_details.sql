-- One-time DDL. Run manually as USER_INFO_SCHEMA in FREEPDB1 using SQL*Plus.
-- An existing USER_DETAILS table causes an error. Inspect it before migrating.
-- Oracle DDL commits implicitly and cannot be undone by ROLLBACK.
-- Passwords are application-generated BCrypt hashes; never insert cleartext.
-- The application trims and lowercases USERNAME and EMAIL before insertion.

SET ECHO OFF
SET VERIFY OFF
SET DEFINE OFF
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE USER_INFO_SCHEMA.USER_DETAILS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USERNAME VARCHAR2(64 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR) NOT NULL,
    PHONE_NUMBER VARCHAR2(32 CHAR) NOT NULL,
    USER_ROLE VARCHAR2(16 CHAR) DEFAULT 'USER' NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    MODIFIED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT USER_DETAILS_PK PRIMARY KEY (ID),
    CONSTRAINT USER_DETAILS_USERNAME_UK UNIQUE (USERNAME),
    CONSTRAINT USER_DETAILS_EMAIL_UK UNIQUE (EMAIL),
    CONSTRAINT USER_DETAILS_ROLE_CK CHECK (USER_ROLE IN ('USER', 'ADMIN')),
    CONSTRAINT USER_DETAILS_ENABLED_CK CHECK (ENABLED IN (0, 1))
);

